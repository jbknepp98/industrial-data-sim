#!/usr/bin/env python3
"""Preview a prepared release-candidate workload offline and check its behavior.

Never connects to a Historian. Each model is copied with a one-minute sampling
interval and the full three-hour live horizon, then generated by the DemoPreview
tool. For manufacturing models the process clock stays at one second, so the
copy is an exact subsample. For generator models the copy shows the pattern
shape at minute resolution; it is review evidence, not the published stream.

The checks below are written independently of the simulator so they can catch
a generator that does not do what the model intends.
"""
import argparse
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import subprocess
import sys

PREVIEW_SAMPLING_MS = 60000
FULL_LIVE = timedelta(hours=3)


def parse(stamp):
    return datetime.fromisoformat(stamp.replace('Z', '+00:00'))


def preview(dotnet, tool, model_path, folder, anchor):
    model = json.loads(model_path.read_text())
    model['samplingIntervalMs'] = PREVIEW_SAMPLING_MS
    start = parse(model['session']['startUtc'])
    # Continuing models get the full live run; the target model keeps its own
    # end because it is expected to stop at its target before then.
    if 'stopOnTarget' not in model_path.read_text():
        model['session']['endUtc'] = (anchor + FULL_LIVE).isoformat().replace('+00:00', 'Z')
    hours = int((parse(model['session']['endUtc']) - start) / timedelta(hours=1)) + 1
    copy = folder / (model_path.stem + '.preview-model.json')
    copy.write_text(json.dumps(model))
    result = subprocess.run([dotnet, str(tool), str(copy), str(min(hours, 96))], capture_output=True, text=True, timeout=600)
    parsed = json.loads(result.stdout)
    if not parsed.get('valid'):
        raise ValueError(f'rc.preview_failed: {model_path.name} did not preview: ' + result.stdout[:400])
    (folder / (model_path.stem + '.preview.json')).write_text(result.stdout)
    return {name: [(parse(p['t']), p['v'], p['q']) for p in points] for name, points in parsed['data'].items()}


def value_at(series, moment):
    """Last value at or before moment, or None before the first sample."""
    current = None
    for stamp, value, _ in series:
        if stamp > moment:
            break
        current = value
    return current


def check(name, condition, failures, detail):
    if not condition:
        failures.append(f'{name}: {detail}')


def check_all(data_by_session, manifest):
    failures, notes = [], []
    anchor = parse(manifest['anchorUtc'])
    for session, data in data_by_session.items():
        for tag, series in data.items():
            stamps = [s for s, _, _ in series]
            check('order', all(a < b for a, b in zip(stamps, stamps[1:])), failures, f'{tag} timestamps not strictly increasing')
    cell = data_by_session['processcell']
    tag = lambda part: next(name for name in cell if name.endswith('.ProcessCell.' + part))
    sku, state, speed_a, speed_b = cell[tag('SKU')], cell[tag('State')], cell[tag('A.Speed')], cell[tag('B.Speed')]
    for stamp, a, _ in speed_a:
        b = value_at(speed_b, stamp)
        current_sku, current_state = value_at(sku, stamp), value_at(state, stamp)
        check('routing', not (a > 0 and b and b > 0), failures, f'both cells running at {stamp}')
        if a > 0:
            check('routing', current_sku == 'SKU-A' and current_state == 'Running', failures, f'cell A running with {current_sku}/{current_state} at {stamp}')
    for stamp, b, _ in speed_b:
        if b > 0:
            check('routing', value_at(sku, stamp) == 'SKU-B' and value_at(state, stamp) == 'Running', failures, f'cell B running off-SKU at {stamp}')
    for total in ('TimeTotal', 'BatchTotal'):
        values = [v for _, v, _ in cell[tag(total)]]
        check('totalizer', all(a <= b for a, b in zip(values, values[1:])), failures, f'ProcessCell {total} decreased')
    notes.append(f"ProcessCell: SKU changes {sum(1 for a, b in zip(sku, sku[1:]) if a[1] != b[1])}, "
                 f"bad-quality samples {sum(1 for s in cell[tag('Temperature')] if s[2] != 192)}")
    line = data_by_session['packaging']
    ready_tag = next(name for name in line if name.endswith('.LineReady'))
    ready = line[ready_tag]
    for gated in (name for name in line if name.split('.')[-2] in ('Filler', 'Labeler', 'Reject', 'Conveyor', 'Capper')):
        leaked = [s for s, _, _ in line[gated] if value_at(ready, s) is False]
        check('gate', not leaked, failures, f'{gated} emitted {len(leaked)} samples while LineReady was false')
    count = next(name for name in line if name.endswith('.Filler.CountTotal'))
    counts = [v for _, v, _ in line[count]]
    check('gate', all(a <= b for a, b in zip(counts, counts[1:])), failures, 'paused Filler.CountTotal went backwards')
    notes.append(f"PackagingLine: LineReady transitions {sum(1 for a, b in zip(ready, ready[1:]) if a[1] != b[1])}")
    reactor = data_by_session['batchreactor']
    produced = next(series for name, series in reactor.items() if name.endswith('.ProducedKg'))
    values = [v for _, v, _ in produced]
    target = manifest['batchReactorTarget']
    check('target', all(a <= b for a, b in zip(values, values[1:])), failures, 'ProducedKg decreased')
    check('target', values and values[-1] == target, failures, f'ProducedKg ended at {values[-1] if values else None}, not {target}')
    finished = produced[-1][0] if produced else None
    check('target', finished is not None and anchor < finished < anchor + timedelta(hours=2), failures,
          'target was not reached inside the initial two-hour live horizon')
    if finished:
        notes.append(f'BatchReactor: reached {target} kg at live +{(finished - anchor).total_seconds() / 60:.0f} min')
    return failures, notes


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('workload', type=Path, help='Folder written by prepare_rc_acceptance.py')
    parser.add_argument('--dotnet', default='dotnet')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    tool = root / 'tools/IndustrialDataSim.DemoPreview/bin/Release/net10.0/IndustrialDataSim.DemoPreview.dll'
    try:
        manifest = json.loads((args.workload / 'manifest.json').read_text())
        anchor = parse(manifest['anchorUtc'])
        folder = args.workload / 'preview'
        folder.mkdir(exist_ok=False)
        data = {Path(s['file']).stem: preview(args.dotnet, tool, args.workload / s['file'], folder, anchor) for s in manifest['sessions']}
        failures, notes = check_all(data, manifest)
        report = {'outcome': 'Passed' if not failures else 'Failed', 'samplingMs': PREVIEW_SAMPLING_MS,
                  'points': {k: sum(len(s) for s in v.values()) for k, v in data.items()},
                  'notes': notes, 'failures': failures[:50], 'failureCount': len(failures), 'historianWrites': 0}
        (folder / 'checks.json').write_text(json.dumps(report, indent=2) + '\n')
        print(json.dumps(report, indent=2))
        sys.exit(1 if failures else 0)
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as error:
        message = str(error) if str(error).startswith('rc.') else 'rc.preview: Preview could not complete. Check the workload folder, a Release build of DemoPreview, and that preview/ does not already exist.'
        print(json.dumps({'outcome': 'Failed', 'message': message}))
        sys.exit(1)
